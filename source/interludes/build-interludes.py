#!/usr/bin/env python3
"""Turns the interlude scripts (source/interludes/*.md) into the INTERLUDE_TEXT data inside chronicle.html.

The scripts are the source: edit the .md, run this, rebuild the site.

    python3 source/interludes/build-interludes.py            # rewrites the block in source/chronicle.html
    python3 source/interludes/build-interludes.py --check    # exits 1 when the block is out of date

Script format (one file per interlude):
  ## K1. Title            a passage; "## End A. Title" is an ending
  plain paragraphs        the read-aloud, in the player's second person; *x* is italic, **x** bold
  -> text (go to K2)      a choice ("Continue" alone is a plain next button)
  -> ... (go to G6A ...)  a jump the engine resolves (see INTERLUDES in chronicle.html)
  -> Fight (go to @deck)  a hand-over to the game by name (the bonus levels: fights, timers, the finish)
  ```log ... ```          a block in the speaker's log type (the Steward's), kept line for line
  ## H4. Title {past}     a vision: {past} or {future} (no tag: the present). Sets the vision's look and sound
  ~past: text~            an intrusion: a line from a vision that bleeds into the passage (past, future, or ~text~ for a whisper)
  -> text (Wisdom save DC 15: go to A / B)   a check with dice: A on a success, B on a failure (a save, or a skill: "Insight DC 14")
  -> text (go to A) +dread                  the haunting gets heavier (or -dread lighter); 0 to 5
  -> text (go to A if dread>=3 / B)         A when the dread is that high, else B ("if dread<3 / B" the other way round)
  *Hub: then go to S1*    under a hub's text: its choices grey out once visited, and when all are done the story goes on at S1
  -> text (go to End 2)  straight to an ending (instead of the endBy table)
  -> Continue to your ending   goes to the ending the earlier choices set
     *Tie line, Hans:* "..."   under a choice in a shared vote: what Hans says when he breaks a tie
  > **Echo: Name.** text  the ending's one-use bonus
  **Sent to Sam:** text   the line of lore that goes to Sam when the player finishes
  - **Label (K3a):** text  in the sections after the endings: extra lore lines per passage reached
  ## Whispers, then "- text" or "- future: text"   lines the haunting may whisper anywhere (more of them as the dread grows)
  ## Cutscene: flake, then "- shot" or "- Stig: line" / "- @future: line"   the shots of an in-engine cutscene, by name
  ## X. Title {again}       the loop: the present played wrong (mirrored, rewinding)
  @boy: "..." / @future: "..."   a line spoken by the boy or the future self (their own look and voice)
  ^^text^^                text the black ash is eating (it crumbles as you read)
  {sound: name}           on its own line: a sound cue starts when a reader gets here
  -> text (go to A) +dread -flicker         the meters a choice moves (dread 0-5; flicker 0-5, how faint the future self is)
Anything marked [SAM?...] is a question for Sam and never shown to players, nor is a "*For Sam ...:*" note at the end of a
"Sent to Sam" line. Lines before the first "---" (the header for Sam) are skipped.
"""
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGE = HERE.parent / "chronicle.html"
FILES = ["s10-katy", "s10-saphira", "s10-stig", "s10-together", "s11-stig"]
START, END = "/* INTERLUDE_TEXT:start (generated by source/interludes/build-interludes.py, do not edit by hand) */", "/* INTERLUDE_TEXT:end */"
# bonus levels: the same script format, but played by their own code (no Echo, nothing sent), so they get their own block
BONUS = ["bonus-steward"]
BSTART, BEND = "/* BONUS_TEXT:start (generated by source/interludes/build-interludes.py, do not edit by hand) */", "/* BONUS_TEXT:end */"
PRE = "\x00pre"
INTR = "\x00intr"
SND = "\x00snd"
COND = "\x00if"
# "?flicker>=3:", "?dread<2:", "?seen P2c:" in front of a paragraph: shown only when it holds (the page checks, iFill)
OPS = {">=": "ge", "<=": "le", "<": "lt", ">": "gt", "=": "eq"}
COND_RE = re.compile(r"^\?\s*(?:(flicker|dread)\s*(>=|<=|<|>|=)\s*(\d)|seen\s+([A-Za-z0-9-]+))\s*:\s*")

SAM = re.compile(r"\s*\[SAM\?[^\]]*\]")
PLACEHOLDER = re.compile(r"\[(how she took the call|whom he prayed to|what the water showed him)[^\]]*\]\s*")
FOR_SAM = re.compile(r"\s*\*For Sam\b[^*]*\*.*$")  # "*For Sam and Claire, level 6:* ..." stays in the script, for the table


def inline(s: str) -> str:
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = re.sub(r"\^\^(.+?)\^\^", r'<span class="hv-ash">\1</span>', s)  # text the black ash is eating
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"\*(.+?)\*", r"<i>\1</i>", s)
    return s


WHO = {"boy": "The boy", "future": "Him"}


def block_html(b: str) -> str:
    if b.startswith(COND):
        cond, rest = b[len(COND):].split("\x00", 1)
        return re.sub(r"^<(\w+)", lambda m: f'<{m.group(1)} data-if="{cond}"', block_html(rest), count=1)
    if b.startswith(SND):
        return f'<i class="hv-snd" data-snd="{b[len(SND):]}" hidden></i>'
    m = re.match(r"^@(\w+):\s*(.+)$", b, re.S)
    if m and m.group(1) in WHO:
        return f'<p class="hv-say" data-who="{m.group(1)}"><span class="hv-who">{WHO[m.group(1)]}</span> {inline(m.group(2))}</p>'
    if b.startswith(INTR):
        kind, text = b[len(INTR):].split("\x00", 1)
        return f'<p class="ic-intr" data-v="{kind}">{inline(text)}</p>'
    if b.startswith(PRE):
        t = b[len(PRE):].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return f'<pre class="pl-slog">{t}</pre>'
    return f"<p>{inline(b)}</p>".replace("\n", "<br>")


def clean(s: str) -> str:
    return SAM.sub("", s).strip()


def parse(name: str) -> dict:
    lines = (HERE / f"{name}.md").read_text(encoding="utf-8").splitlines()
    title = lines[0].lstrip("# ").strip()
    i = next(n for n, l in enumerate(lines) if l.strip() == "---") + 1
    passages, ends, extra, whispers, cuts = {}, {}, {}, [], {}
    cur = None  # (kind, id)
    para: list[str] = []
    body: list[str] = []

    def flush_para():
        conds = []
        while para and COND_RE.match(para[0]):
            m = COND_RE.match(para[0])
            conds.append(f"seen:{m.group(4)}" if m.group(4) else f"{m.group(1)}:{OPS[m.group(2)]}:{m.group(3)}")
            para[0] = para[0][m.end():]
        if conds:
            n = len(body)
            flush_para()
            for k in range(n, len(body)):
                body[k] = COND + "&".join(conds) + "\x00" + body[k]
            return
        if len(para) == 1 and re.match(r"^\{sound:\s*[\w-]+\s*\}$", para[0]):
            body.append(SND + re.match(r"^\{sound:\s*([\w-]+)", para[0]).group(1))
            para.clear()
            return
        if len(para) == 1 and re.match(r"^~.+~$", para[0]):
            m2 = re.match(r"^~\s*(?:(past|future):\s*)?(.+?)\s*~$", para[0])
            body.append(INTR + (m2.group(1) or "whisper") + "\x00" + clean(m2.group(2)))
            para.clear()
            return
        if para:
            verse = len(para) > 1 and all(l.startswith("*") and l.endswith("*") for l in para)
            text = clean(("\n" if verse else " ").join(para))
            if text:
                body.append(text)
            para.clear()

    def close():
        flush_para()
        if not cur:
            return
        kind, pid = cur
        if kind == "p":
            passages[pid]["html"] = "".join(block_html(b) for b in body)
        elif kind == "e":
            ends[pid]["html"] = "".join(block_html(b) for b in body)
        body.clear()

    fence: list[str] | None = None
    for raw in lines[i:]:
        line = raw.rstrip()
        if fence is not None:  # inside a ```log block: kept line for line
            if line.strip() == "```":
                body.append(PRE + "\n".join(fence))
                fence = None
            else:
                fence.append(line)
            continue
        if line.strip() == "```log" and cur:
            flush_para()
            fence = []
            continue
        m = re.match(r"^## (End (\w+)|([A-Z][A-Za-z0-9-]*))\. (.+)$", line)
        if m:
            close()
            head, tags = m.group(4).strip(), []
            while True:  # "## L1. Again {again}", "## X. Title {past} {again}"
                t = re.search(r"\s*\{\s*(past|future|now|again)\s*(?:,[^}]*)?\}\s*$", head)
                if not t:
                    break
                head, tags = head[: t.start()].strip(), [t.group(1)] + tags
            tag = next((x for x in tags if x in ("past", "future")), None)
            if m.group(2):
                cur = ("e", m.group(2))
                ends[cur[1]] = {"h": head, "html": "", "echo": None, "lore": ""}
            else:
                cur = ("p", m.group(3))
                passages[cur[1]] = {"h": head, "html": "", "opts": []}
                if tag:
                    passages[cur[1]]["v"] = tag
                if "again" in tags:
                    passages[cur[1]]["again"] = 1
            continue
        if line.startswith("## "):  # the sections after the endings
            close()
            cur = ("x", line[3:].strip())
            continue
        if line.strip() == "---":
            continue
        if cur is None:
            continue
        kind, pid = cur
        m = re.match(r"^→\s*(.+?)\s*$", line)
        if m and kind == "p":
            flush_para()
            t = m.group(1)
            opt = {}
            while True:  # "+dread", "-flicker", "+dread -flicker": the meters a choice moves
                d = re.search(r"\s*([+-])(\d*)\s*(dread|flicker)\s*$", t)
                if not d:
                    break
                opt[d.group(3)] = opt.get(d.group(3), 0) + (1 if d.group(1) == "+" else -1) * int(d.group(2) or 1)
                t = t[: d.start()].rstrip()
            c = re.search(r"\((?:(\w+) (save|saving throw)|([A-Za-z ]+?)) DC (\d+): go to ([A-Za-z0-9-]+) / ([A-Za-z0-9-]+)\)\s*$", t)
            k = re.search(r"\(go to ([A-Za-z0-9-]+) if dread\s*(>=|<)\s*(\d) / ([A-Za-z0-9-]+)\)\s*$", t)
            e = re.search(r"\(go to End (\w+)\)\s*$", t)
            g = re.search(r"\(go to (@?[A-Za-z0-9-]+)[^)]*\)\s*$", t)
            if c:
                ab = (c.group(1) or "").lower()[:3] if c.group(2) else None
                opt["check"] = {"save": ab, "skill": None if ab else c.group(3).strip().lower(), "dc": int(c.group(4)),
                                "label": (c.group(1).capitalize() + " save") if ab else c.group(3).strip()}
                passages[pid]["opts"].append({"t": clean(t[: c.start()].strip()), "go": c.group(5), "fail": c.group(6), **opt})
                continue
            if k:
                hi, lo = (k.group(1), k.group(4)) if k.group(2) == ">=" else (k.group(4), k.group(1))  # "if dread>=4 / B" or "if dread<4 / B"
                passages[pid]["opts"].append({"t": clean(t[: k.start()].strip()), "go": lo, "alt": {"min": int(k.group(3)), "go": hi}, **opt})
                continue
            if e:
                passages[pid]["opts"].append({"t": clean(t[: e.start()].strip()), "go": "@end:" + e.group(1), **opt})
                continue
            if g:
                text = t[: g.start()].strip()
                go = g.group(1)
                if "," in t[g.start():] and "version" in t[g.start():]:
                    go = "@" + go
            elif t.lower().startswith("continue to your ending"):
                text, go = "Continue", "@end"
            else:
                raise SystemExit(f"{name}: a choice without a target in {pid}: {t}")
            passages[pid]["opts"].append({"t": clean(text), "go": go, **opt})
            continue
        m = re.match(r"^\s+\*Tie line, Hans:\*\s*(.+)$", line)
        if m and kind == "p":
            passages[pid]["opts"][-1]["tie"] = clean(m.group(1)).strip('"“” ')
            continue
        m = re.match(r"^>\s*\*\*Echo: (.+?)\.\*\*\s*(.+)$", line)
        if m and kind == "e":
            flush_para()
            ends[pid]["echo"] = {"name": m.group(1), "text": clean(m.group(2))}
            continue
        m = re.match(r"^\*\*Sent to Sam:\*\*\s*(.+)$", line)
        if m and kind == "e":
            flush_para()
            ends[pid]["lore"] = re.sub(r"\*+", "", clean(FOR_SAM.sub("", PLACEHOLDER.sub("", m.group(1)))))
            continue
        m = re.match(r"^\*Hub: then go to ([A-Za-z0-9-]+)\*\s*$", line)
        if m and kind == "p":  # a hub: its choices grey out once visited; when all are done the story goes on here
            passages[pid]["then"] = m.group(1)
            continue
        if kind == "x" and re.match(r"(?i)^cutscene:", pid):
            m = re.match(r"^[-*]\s+(.+)$", line)
            if m:
                key = re.sub(r"\s+", "", pid.split(":", 1)[1]).lower()
                t = clean(m.group(1)).strip()
                sm = re.match(r"^(@?\w+):\s*(.+)$", t)
                who = sm.group(1).lstrip("@").lower() if sm and sm.group(1).lstrip("@").lower() in ("stig", "boy", "future") else None
                cuts.setdefault(key, []).append({"who": who, "t": re.sub(r"\*+", "", sm.group(2) if who else t)})
            continue
        if kind == "x" and re.match(r"(?i)^(whispers|intrusions)\b", pid):
            m = re.match(r"^[-*]\s+(?:(past|future):\s*)?(.+)$", line)
            if m and clean(m.group(2)):
                whispers.append({"v": m.group(1) or "whisper", "t": re.sub(r"^[\"“]|[\"”]$", "", re.sub(r"\*+", "", clean(m.group(2))).strip())})
            continue
        if kind == "x":
            m = re.match(r"^- \*\*.+?\(([A-Za-z0-9-]+)\):\*\*\s*(.+)$", line) or re.match(r"^\*\*.+?\(([A-Za-z0-9-]+)\), sent to Sam:\*\*\s*(.+)$", line)
            if m:
                extra[m.group(1)] = re.sub(r"\*+", "", clean(m.group(2)))
            continue
        if not line.strip():
            flush_para()
        else:
            para.append(line.strip())
    close()
    # sanity: every target exists, and every "?seen X:" names a passage
    for html in [p["html"] for p in passages.values()] + [e["html"] for e in ends.values()]:
        for cid in re.findall(r'seen:([A-Za-z0-9-]+)', html):
            if cid not in passages:
                raise SystemExit(f"{name}: ?seen {cid} isn't a passage")
    for pid, p in passages.items():
        for o in p["opts"]:
            for g in [o["go"], o.get("fail"), (o.get("alt") or {}).get("go"), p.get("then") if o is p["opts"][0] else None]:
                if not g:
                    continue
                if g.startswith("@end:"):
                    if g[5:] not in ends:
                        raise SystemExit(f"{name}: {pid} points at End {g[5:]}, which isn't an ending")
                    continue
                if g.startswith("@"):
                    continue
                if g not in passages:
                    raise SystemExit(f"{name}: {pid} points at {g}, which isn't a passage")
    first = next(iter(passages))
    out = {"title": title, "first": first, "passages": passages, "ends": ends, "extra": extra}
    if whispers:
        out["whispers"] = whispers
    if cuts:
        out["cuts"] = cuts
    return out


def put(page: str, start: str, end: str, name: str, data: dict) -> str:
    block = start + f"\nconst {name}=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n" + end
    a, b = page.find(start), page.find(end)
    if a < 0 or b < 0:
        raise SystemExit(f"{name} markers not found in chronicle.html")
    return page[:a] + block + page[b + len(end):]


def main():
    data = {n: parse(n) for n in FILES if (HERE / f"{n}.md").exists()}
    bonus = {n: parse(n) for n in BONUS}
    page = PAGE.read_text(encoding="utf-8")
    new = put(put(page, START, END, "INTERLUDE_TEXT", data), BSTART, BEND, "BONUS_TEXT", bonus)
    if "--check" in sys.argv:
        sys.exit(0 if new == page else 1)
    if new != page:
        PAGE.write_text(new, encoding="utf-8")
    n = sum(len(d["passages"]) for d in data.values())
    print(f"INTERLUDE_TEXT: {len(data)} interludes, {n} passages, {sum(len(d['ends']) for d in data.values())} endings")
    print(f"BONUS_TEXT: {len(bonus)} levels, {sum(len(d['passages']) for d in bonus.values())} passages")


if __name__ == "__main__":
    main()
